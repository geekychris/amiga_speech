static const struct { const char *name; int vowel, cons; } contractions[] = {
    { "UL", PH_AX, PH_L }, { "IL", PH_IX, PH_L },
    { "UM", PH_AX, PH_M }, { "IM", PH_IX, PH_M },
    { "UN", PH_AX, PH_N }, { "IN", PH_IX, PH_N },
};

static int up(int c) { return (c >= 'a' && c <= 'z') ? c - 32 : c; }

int ph_lookup(const char *s, int avail, int *used, int *second)
{
    int i;
    *second = -1;
    if (avail <= 0)
        return -1;
    /* two-character codes first (greedy), then single */
    if (avail >= 2) {
        char a = (char)up((unsigned char)s[0]), b = (char)up((unsigned char)s[1]);
        for (i = 1; i < PH_COUNT; i++) {
            const char *n = ph_table[i].name;
            if (n[0] == a && n[1] == b && n[2] == 0) {
                *used = 2;
                return i;
            }
        }
        for (i = 0; i < (int)(sizeof contractions / sizeof contractions[0]); i++) {
            if (contractions[i].name[0] == a && contractions[i].name[1] == b) {
                *used = 2;
                *second = contractions[i].cons;
                return contractions[i].vowel;
            }
        }
    }
    {
        char a = (char)up((unsigned char)s[0]);
        for (i = 1; i < PH_COUNT; i++) {
            const char *n = ph_table[i].name;
            if (n[0] == a && n[1] == 0) {
                *used = 1;
                return i;
            }
        }
    }
    return -1;
}
